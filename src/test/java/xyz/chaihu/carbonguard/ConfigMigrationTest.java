package xyz.chaihu.carbonguard;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.bukkit.configuration.file.YamlConfiguration;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import xyz.chaihu.carbonguard.config.CarbonGuardConfig;
import xyz.chaihu.carbonguard.config.ConfigLoader;

/** Old configs must keep working and be upgraded on disk without losing operator values. */
class ConfigMigrationTest {
    @TempDir
    Path tempDir;

    private static final String V1_CONFIG = """
            config-version: 1
            debug: true
            email-verify:
              enable: true
              require-binding: true
              ticket-ttl-seconds: 1800
              require-qq-email: true
              allowed-email-domains: [ "qq.com", "vip.qq.com" ]
            ip-limit:
              max-accounts-per-ip: 5
            smtp:
              host: "smtp.example.com"
              from: "bot@example.com"
            """;

    @Test
    void v1ConfigIsMigratedOnDiskWithBackup() throws Exception {
        Path configFile = tempDir.resolve("config.yml");
        Files.writeString(configFile, V1_CONFIG);

        ConfigLoader.LoadResult loaded = ConfigLoader.loadFile(configFile, tempDir);
        CarbonGuardConfig config = loaded.config();

        assertEquals(CarbonGuardConfig.CONFIG_VERSION, config.configVersion());
        assertTrue(config.debug(), "operator values must survive migration");
        assertEquals(5, config.ipLimit().maxAccountsPerIp());
        assertEquals("smtp.example.com", config.smtp().host());
        assertTrue(config.binding().enable(), "binding section is added with defaults");
        assertEquals("/bind", config.binding().verifyPath());
        assertTrue(loaded.warnings().stream().anyMatch(w -> w.contains("config-version 已自动升级")));

        YamlConfiguration rewritten = new YamlConfiguration();
        rewritten.load(configFile.toFile());
        assertEquals(CarbonGuardConfig.CONFIG_VERSION, rewritten.getInt("config-version"));
        assertTrue(rewritten.contains("binding.enable"));
        assertTrue(rewritten.contains("debug"), "unrelated keys must be preserved");
        assertFalse(rewritten.contains("email-verify.ticket-ttl-seconds"), "removed option is dropped");
        assertFalse(rewritten.contains("email-verify.allowed-email-domains"));

        // A timestamped copy of the original v1 file must be kept next to it.
        List<Path> backups;
        try (var stream = Files.list(tempDir)) {
            backups = stream
                    .filter(p -> p.getFileName().toString().startsWith("config.")
                            && p.getFileName().toString().endsWith(".yml")
                            && !p.getFileName().toString().equals("config.yml"))
                    .toList();
        }
        assertEquals(1, backups.size(), "exactly one backup: " + backups);
        YamlConfiguration backup = new YamlConfiguration();
        backup.load(backups.get(0).toFile());
        assertEquals(1, backup.getInt("config-version"));
        assertEquals("true", backup.getString("email-verify.require-binding"));
    }

    @Test
    void generatedAdminKeyIsPersistedInTheSameWriteAsTheMigration() throws Exception {
        Path configFile = tempDir.resolve("config.yml");
        Files.writeString(configFile, """
                config-version: 1
                web:
                  public-url: "https://cg.example.com"
                binding:
                  verify-url: "/bind"
                """);
        ConfigLoader.LoadResult loaded = ConfigLoader.loadFile(configFile, tempDir);
        assertTrue(loaded.config().web().adminKeyAutoGenerated());

        YamlConfiguration rewritten = new YamlConfiguration();
        rewritten.load(configFile.toFile());
        // The migration must not be lost when the admin key is written afterwards.
        assertTrue(rewritten.contains("binding.enable"), "migrated keys survive the admin-key write");
        assertEquals(CarbonGuardConfig.CONFIG_VERSION, rewritten.getInt("config-version"));
        assertTrue(CarbonGuardConfig.Web.isAdminKeyStrong(rewritten.getString("web.admin-key")));
        // The generated key is the one the running config uses.
        assertEquals(rewritten.getString("web.admin-key"), loaded.config().web().adminKey());
    }

    @Test
    void currentConfigIsNotRewritten() throws Exception {
        Path configFile = tempDir.resolve("config.yml");
        Files.writeString(configFile, """
                config-version: %d
                binding:
                  enable: true
                  verify-url: "/bind"
                  show-avatars: false
                """.formatted(CarbonGuardConfig.CONFIG_VERSION));

        ConfigLoader.LoadResult loaded = ConfigLoader.loadFile(configFile, tempDir);
        assertEquals(CarbonGuardConfig.CONFIG_VERSION, loaded.config().configVersion());
        assertFalse(loaded.config().binding().showAvatars());
        try (var stream = Files.list(tempDir)) {
            assertEquals(1, stream.count(), "no backup is created for an up-to-date config");
        }
    }

    @Test
    void legacyBindingKeysOnlyWarn() {
        YamlConfiguration yaml = new YamlConfiguration();
        yaml.set("config-version", CarbonGuardConfig.CONFIG_VERSION);
        yaml.set("binding.require-email-code", false);
        yaml.set("binding.require-email-domain", "");
        ConfigLoader.LoadResult loaded = ConfigLoader.load(yaml, tempDir);
        assertTrue(loaded.warnings().stream().anyMatch(w -> w.contains("固定为 ID@qq.com")));
    }
}
